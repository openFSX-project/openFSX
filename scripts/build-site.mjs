// Small, deterministic renderer for the Markdown subset used by this repository.
// All HTML is escaped; no raw HTML, scripts or remote content are accepted.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const sources = ['docs/VIEWER.md', 'docs/ARCHITECTURE.md', 'docs/COMPATIBILITY.md', 'docs/FORMATS.md', 'CONTRIBUTING.md'];
const escape = value => value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", '&#39;');
function inline(text) {
  const token = /(`[^`]+`|\[[^\]]+\]\([^)]+\)|\*\*[^*]+\*\*)/g;
  let output = '', end = 0;
  for (const match of text.matchAll(token)) {
    output += escape(text.slice(end, match.index));
    const raw = match[0];
    if (raw.startsWith('`')) output += `<code>${escape(raw.slice(1, -1))}</code>`;
    else if (raw.startsWith('**')) output += `<strong>${escape(raw.slice(2, -2))}</strong>`;
    else {
      const [, label, target] = raw.match(/^\[([^\]]+)\]\(([^)]+)\)$/);
      const doc = target.match(/(?:^|\/)([A-Z_]+)\.md$/);
      const url = doc ? `#/docs/${doc[1]}` : target;
      if (!url.startsWith('https://') && !url.startsWith('#/docs/')) throw new Error(`Unsupported Markdown link: ${url}`);
      output += `<a href="${escape(url)}">${escape(label)}</a>`;
    }
    end = match.index + raw.length;
  }
  return output + escape(text.slice(end));
}
function render(markdown) {
  const lines = markdown.replaceAll('\r\n', '\n').trim().split('\n');
  const output = [];
  for (let i = 0; i < lines.length;) {
    const line = lines[i];
    if (!line.trim()) { i++; continue; }
    if (line.startsWith('```')) {
      const code = []; i++;
      while (i < lines.length && !lines[i].startsWith('```')) code.push(lines[i++]);
      if (i === lines.length) throw new Error('Unclosed code block');
      i++; output.push(`<pre><code>${escape(code.join('\n'))}</code></pre>`); continue;
    }
    const heading = line.match(/^(#{1,6}) (.+)$/);
    if (heading) { output.push(`<h${heading[1].length}>${inline(heading[2])}</h${heading[1].length}>`); i++; continue; }
    if (line.startsWith('|')) {
      const rows = [];
      while (i < lines.length && lines[i].startsWith('|')) rows.push(lines[i++].split('|').slice(1, -1).map(s => s.trim()));
      if (rows.length < 2 || !rows[1].every(cell => /^:?-+:?$/.test(cell))) throw new Error('Invalid Markdown table');
      const width = rows[0].length;
      if (rows.some(row => row.length !== width)) throw new Error('Mismatched table columns');
      output.push('<div class="table-wrap"><table><thead><tr>' + rows[0].map(cell => `<th scope="col">${inline(cell)}</th>`).join('') + '</tr></thead><tbody>' + rows.slice(2).map(row => '<tr>' + row.map(cell => `<td>${inline(cell)}</td>`).join('') + '</tr>').join('') + '</tbody></table></div>'); continue;
    }
    if (/^(?:- |\d+\. )/.test(line)) {
      const ordered = /^\d/.test(line), tag = ordered ? 'ol' : 'ul', items = [];
      const pattern = ordered ? /^\d+\. / : /^- /;
      while (i < lines.length && pattern.test(lines[i])) items.push(`<li>${inline(lines[i++].replace(pattern, ''))}</li>`);
      output.push(`<${tag}>${items.join('')}</${tag}>`); continue;
    }
    const paragraph = [];
    while (i < lines.length && lines[i].trim() && !/^(#{1,6} |```|\||- |\d+\. )/.test(lines[i])) paragraph.push(lines[i++]);
    output.push(`<p>${inline(paragraph.join(' '))}</p>`);
  }
  return output.join('\n');
}
const docs = {};
for (const source of sources) {
  const markdown = await readFile(new URL(source, root), 'utf8');
  const id = source.split('/').at(-1).replace('.md', '');
  docs[id] = { source, title: markdown.match(/^# (.+)$/m)[1], html: render(markdown) };
}
const result = '// Generated by scripts/build-site.mjs. Edit docs/ or CONTRIBUTING.md.\n' + `globalThis.OPENFSX_DOCS = ${JSON.stringify(docs, null, 2)};\n`;
const target = new URL('site/docs.js', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== result) throw new Error('Site documentation is stale. Run node scripts/build-site.mjs');
  console.log('Site documentation is up to date.');
} else {
  await writeFile(target, result);
  console.log(`Generated ${Object.keys(docs).length} documents: ${fileURLToPath(target)}`);
}
