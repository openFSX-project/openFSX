(() => {
  const drawer = document.getElementById('drawer');
  const menu = document.getElementById('menu-button');
  const scrim = document.getElementById('scrim');
  const main = document.getElementById('main');
  const docView = document.getElementById('documentation');
  const docs = globalThis.OPENFSX_DOCS || {};
  const themeButton = document.getElementById('theme-button');
  const mobile = window.matchMedia('(max-width: 900px)');
  const media = window.matchMedia('(prefers-color-scheme: dark)');
  let theme = 'system';
  try { theme = localStorage.getItem('openfsx-theme') || 'system'; } catch {}
  if (!['system', 'light', 'dark'].includes(theme)) theme = 'system';
  function applyTheme() {
    document.documentElement.dataset.theme = theme === 'system' ? (media.matches ? 'dark' : 'light') : theme;
    themeButton.setAttribute('aria-label', `Theme: ${theme}. Activate to change.`);
    themeButton.title = `Theme: ${theme}`;
  }
  themeButton.addEventListener('click', () => {
    theme = { system: 'light', light: 'dark', dark: 'system' }[theme];
    try { localStorage.setItem('openfsx-theme', theme); } catch {}
    applyTheme();
  });
  media.addEventListener('change', applyTheme);
  applyTheme();
  function setDrawer(open) {
    open = open && mobile.matches;
    drawer.classList.toggle('open', open);
    drawer.inert = mobile.matches && !open;
    scrim.hidden = !open;
    menu.setAttribute('aria-expanded', String(open));
    menu.setAttribute('aria-label', open ? 'Close navigation' : 'Open navigation');
  }
  menu.addEventListener('click', () => setDrawer(menu.getAttribute('aria-expanded') !== 'true'));
  scrim.addEventListener('click', () => setDrawer(false));
  document.addEventListener('keydown', event => { if (event.key === 'Escape' && menu.getAttribute('aria-expanded') === 'true') { setDrawer(false); menu.focus(); } });
  mobile.addEventListener('change', () => setDrawer(false));
  document.querySelector('.skip').addEventListener('click', event => { event.preventDefault(); main.focus(); });
  drawer.addEventListener('click', event => { if (event.target.closest('a')) setDrawer(false); });
  let toastTimer;
  function toast(message) {
    const element = document.getElementById('toast');
    element.textContent = message;
    element.hidden = false;
    clearTimeout(toastTimer);
    toastTimer = setTimeout(() => { element.hidden = true; }, 2500);
  }
  function addCopyButtons() {
    main.querySelectorAll('pre').forEach(pre => {
      if (pre.querySelector('button')) return;
      const button = document.createElement('button');
      button.type = 'button'; button.className = 'copy-button'; button.textContent = 'Copy';
      button.setAttribute('aria-label', 'Copy code block');
      button.addEventListener('click', async () => {
        try { await navigator.clipboard.writeText(pre.querySelector('code').textContent); toast('Copied to clipboard'); }
        catch { toast('Copy unavailable. Select the code to copy it.'); }
      });
      pre.append(button);
    });
  }
  function route(focus) {
    const path = location.hash.slice(1) || '/';
    let title = 'Overview';
    document.querySelectorAll('.route').forEach(page => { page.hidden = true; });
    if (path === '/' || path === '/download') {
      document.getElementById(path === '/' ? 'overview' : 'download').hidden = false;
      title = path === '/' ? 'Overview' : 'Get started';
    } else if (path.startsWith('/docs/') && Object.hasOwn(docs, path.slice(6))) {
      const doc = docs[path.slice(6)];
      // HTML is generated by our escaping Markdown builder from tracked docs, never remote input.
      docView.innerHTML = `<p class="breadcrumb">openFSX / Documentation</p>${doc.html}<p class="doc-source"><a href="https://github.com/openFSX-project/openFSX/blob/main/${doc.source}">View this document on GitHub ↗</a></p>`;
      docView.hidden = false; title = doc.title;
    } else {
      document.getElementById('not-found').hidden = false; title = 'Page not found';
    }
    document.title = title === 'Overview' ? 'openFSX — Independent flight simulation' : `${title} — openFSX`;
    document.querySelectorAll('[data-route]').forEach(link => {
      if (link.dataset.route === path) link.setAttribute('aria-current', 'page');
      else link.removeAttribute('aria-current');
    });
    setDrawer(false); addCopyButtons();
    if (focus) { window.scrollTo(0, 0); main.focus({ preventScroll: true }); }
  }
  window.addEventListener('hashchange', () => route(true));
  route(false);
})();
